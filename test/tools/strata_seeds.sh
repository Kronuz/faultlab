# Regenerates test/strata_seeds.inc from strata's faultfs at STRATA_COMMIT, with completion's io.h
# at COMPLETION_COMMIT: strata_seeds.sh STRATA_CHECKOUT COMPLETION_CHECKOUT > test/strata_seeds.inc
set -eu
STRATA=$1
COMPLETION=$2
STRATA_COMMIT=${STRATA_COMMIT:-491a1bdc2aa1e8856b9d7a583e90c4fabf673998}
COMPLETION_COMMIT=${COMPLETION_COMMIT:-d8b538c6778f0a1b969e42c8428995d1d29d4731}
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${OUT:-$HERE/../../.scratch/strata-seeds}
mkdir -p "$OUT/inc/strata/core" "$OUT/inc/completion"
git -C "$STRATA" show "$STRATA_COMMIT:include/strata/core/faultfs.hh" > "$OUT/inc/strata/core/faultfs.hh"
git -C "$COMPLETION" show "$COMPLETION_COMMIT:include/completion/io.h" > "$OUT/inc/completion/io.h"
${CXX:-c++} -std=c++20 -O1 -I"$OUT/inc" "$HERE/strata_seeds.cc" -o "$OUT/strata_seeds"
echo "// strata:$STRATA_COMMIT include/strata/core/faultfs.hh, completion:$COMPLETION_COMMIT io.h"
echo "// Generated by test/tools/strata_seeds.sh: {scenario, seed, fingerprint after crash(seed)}."
"$OUT/strata_seeds"
